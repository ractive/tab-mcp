/**
 * Writes src/icons.ts from scripts/favicon.svg: the SVG as text, and
 * favicon.ico (16, 32 and 48 px) and apple-touch-icon.png (180 px) rendered
 * with ImageMagick (`magick` on the PATH). Run after changing the SVG:
 *
 *   bun scripts/favicon.ts
 */

import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { $ } from "bun";

const here = import.meta.dir;
const svgPath = join(here, "favicon.svg");
const svg = (await Bun.file(svgPath).text()).trim();
const dir = await mkdtemp(join(tmpdir(), "tab-mcp-favicon-"));
try {
	const render = (size: number, out: string) =>
		$`magick -background none -density 600 ${svgPath} -resize ${size}x${size} -strip ${out}`.quiet();
	const sizes = [16, 32, 48];
	for (const s of sizes) await render(s, join(dir, `${s}.png`));
	await $`magick ${sizes.map((s) => join(dir, `${s}.png`))} ${join(dir, "favicon.ico")}`.quiet();
	await render(180, join(dir, "touch.png"));
	const b64 = async (name: string) =>
		Buffer.from(await Bun.file(join(dir, name)).arrayBuffer()).toString(
			"base64",
		);
	const out = `// Generated by scripts/favicon.ts from scripts/favicon.svg; do not edit.

/** The relay's icon: a browser tab with two linked dots. */
export const FAVICON_SVG: string = ${JSON.stringify(svg)};

/** favicon.ico: 16, 32 and 48 px. */
export const FAVICON_ICO: Uint8Array<ArrayBuffer> = new Uint8Array(
	Buffer.from("${await b64("favicon.ico")}", "base64"),
);

/** apple-touch-icon.png: 180 px. */
export const APPLE_TOUCH_ICON: Uint8Array<ArrayBuffer> = new Uint8Array(
	Buffer.from("${await b64("touch.png")}", "base64"),
);
`;
	await Bun.write(join(here, "../src/icons.ts"), out);
} finally {
	await rm(dir, { recursive: true, force: true });
}

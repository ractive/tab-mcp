/**
 * Writes src/oauth/code-field-script.ts from src/oauth/code-field-page.ts:
 * the pairing page's one script (DEC-211), bundled for the browser, as text.
 * The page ships it inline and its policy allows it by the hash the relay
 * computes from that text when it starts. Run after changing
 * `code-field-page.ts` or `code-field.ts`:
 *
 *   bun scripts/code-field.ts
 *
 * The relay's tests fail while the file is out of date.
 */

import { join } from "node:path";
import { $ } from "bun";

const root = join(import.meta.dir, "..");
const target = join(root, "src/oauth/code-field-script.ts");

/** The script as the page ships it. */
export async function buildCodeFieldScript(): Promise<string> {
	const result = await Bun.build({
		entrypoints: [join(root, "src/oauth/code-field-page.ts")],
		target: "browser",
		format: "iife",
		// Short, but with its names, so the page's source stays readable.
		minify: { whitespace: true, syntax: true, identifiers: false },
	});
	const [output] = result.outputs;
	if (!result.success || output === undefined) {
		throw new AggregateError(result.logs, "the code field script failed");
	}
	const script = (await output.text()).trim();
	// Inline in a <script> element: these would end it or change its parsing.
	if (/<\/script|<!--/i.test(script)) {
		throw new Error("the code field script contains </script or <!--");
	}
	return script;
}

if (import.meta.main) {
	const script = await buildCodeFieldScript();
	await Bun.write(
		target,
		`// Generated by scripts/code-field.ts from src/oauth/code-field-page.ts; do not edit.
// biome-ignore-all lint/suspicious/noTemplateCurlyInString: the script's own template literals

/** The pairing page's one script (DEC-211): it draws the code field as boxes. */
export const CODE_FIELD_SCRIPT: string = ${JSON.stringify(script)};
`,
	);
	// The repository's formatting, so `bun run verify` passes as written.
	await $`bunx biome format --write ${target}`.quiet();
	console.log(`  ${target.slice(root.length + 1)} ${script.length} bytes`);
}
